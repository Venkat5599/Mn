/**
 * Builds the contracts and writes typed `as const` ABIs into packages/shared/src/abi.
 * Run after any contract change: `bun run abi`.
 */
import { $ } from "bun";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const outDir = join(root, "packages/shared/src/abi");

const CONTRACTS = [
  { file: "PitchOracle.sol", name: "PitchOracle", exportName: "pitchOracleAbi" },
  { file: "PitchsideRooms.sol", name: "PitchsideRooms", exportName: "pitchsideRoomsAbi" },
  { file: "MockAUSD.sol", name: "MockAUSD", exportName: "mockAusdAbi" },
] as const;

await $`forge build --silent`.cwd(join(root, "contracts"));
await mkdir(outDir, { recursive: true });

const index: string[] = [];
for (const c of CONTRACTS) {
  const artifact = await Bun.file(join(root, "contracts/out", c.file, `${c.name}.json`)).json();
  const fileName = c.exportName.replace(/Abi$/, "");
  const body =
    `// Generated by scripts/gen-abi.ts from contracts/src/**/${c.file}. Do not edit.\n` +
    `export const ${c.exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  await Bun.write(join(outDir, `${fileName}.ts`), body);
  index.push(`export { ${c.exportName} } from "./${fileName}";`);
  console.log(`abi: ${c.name} (${artifact.abi.length} entries)`);
}
await Bun.write(join(outDir, "index.ts"), `${index.join("\n")}\n`);
