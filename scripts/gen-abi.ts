/**
 * Builds the contracts and writes typed `as const` ABIs into packages/sdk/src/abi.
 * Run after any contract change: `bun run abi`.
 */
import { $ } from "bun";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const contracts = join(root, "packages/contracts");
const outDir = join(root, "packages/sdk/src/abi");

const CONTRACTS = [
  { file: "ComputeMarket.sol", name: "ComputeMarket", exportName: "computeMarketAbi" },
  { file: "CollateralVault.sol", name: "CollateralVault", exportName: "collateralVaultAbi" },
  { file: "OracleVerifier.sol", name: "OracleVerifier", exportName: "oracleVerifierAbi" },
  { file: "PriceProtectionPool.sol", name: "PriceProtectionPool", exportName: "priceProtectionPoolAbi" },
  { file: "PositionListings.sol", name: "PositionListings", exportName: "positionListingsAbi" },
] as const;

await $`forge build --silent`.cwd(contracts);
await mkdir(outDir, { recursive: true });

const index: string[] = [];
for (const c of CONTRACTS) {
  const artifact = await Bun.file(join(contracts, "out", c.file, `${c.name}.json`)).json();
  const fileName = c.exportName.replace(/Abi$/, "");
  const body =
    `// Generated by scripts/gen-abi.ts from ${c.file}. Do not edit.\n` +
    `export const ${c.exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  await Bun.write(join(outDir, `${fileName}.ts`), body);
  index.push(`export { ${c.exportName} } from "./${fileName}";`);
  console.log(`abi: ${c.name} (${artifact.abi.length} entries)`);
}
await Bun.write(join(outDir, "index.ts"), `${index.join("\n")}\n`);
